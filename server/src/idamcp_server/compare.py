"""Multi-database comparison (feature group H), computed in the MCP server from per-function
fingerprints fetched page by page from each IDA instance (bridge method
`function_fingerprints`), so IDA's UI thread is only held for short, bounded calls.

Matching stages, in order:
  1. name        - identical non-autogenerated names (confidence 1.0)
  2. exact_bytes - identical byte hash, unique on both sides (0.99)
  3. normalized  - identical mnemonic+operand-type sequence, unique on both sides (0.95)
  4. similarity  - weighted score over mnemonic histogram, size, CFG shape, callees and
                   strings (heuristic; confidence = score)
Similarity never proves functional equivalence.
"""

from __future__ import annotations

import math
from collections import Counter
from typing import Any, Awaitable, Callable

Fetch = Callable[[str | None], Awaitable[list[dict[str, Any]]]]

HEURISTIC_NOTE = ("Heuristic matches (method 'similarity') are based on instruction statistics, CFG shape, "
                  "callees and strings. A high score suggests, but does not prove, that two functions are "
                  "equivalent.")


async def fetch_fingerprints(call: Callable[..., Awaitable[Any]], database: str | None,
                             max_functions: int, timeout_ms: int) -> tuple[list[dict[str, Any]], bool]:
    """All function fingerprints of one database (bounded by max_functions)."""
    out: list[dict[str, Any]] = []
    offset = 0
    while len(out) < max_functions:
        page = await call(database, "function_fingerprints", timeout_ms=timeout_ms, offset=offset,
                          limit=min(200, max_functions - len(out)))
        out.extend(page["items"])
        nxt = page.get("next_offset")
        if nxt is None:
            return out, False
        if nxt == offset:  # deadline hit without progress: avoid looping forever
            raise RuntimeError("fingerprinting made no progress (IDA busy?)")
        offset = nxt
    return out, True


def _cosine(a: dict[str, int], b: dict[str, int]) -> float:
    keys = set(a) | set(b)
    dot = sum(a.get(k, 0) * b.get(k, 0) for k in keys)
    na = math.sqrt(sum(v * v for v in a.values()))
    nb = math.sqrt(sum(v * v for v in b.values()))
    return dot / (na * nb) if na and nb else 0.0


def _ratio(x: float, y: float) -> float:
    if x <= 0 and y <= 0:
        return 1.0
    return min(x, y) / max(x, y) if max(x, y) > 0 else 0.0


def _jaccard(a: list[str], b: list[str]) -> float | None:
    sa, sb = set(a), set(b)
    if not sa and not sb:
        return None
    return len(sa & sb) / len(sa | sb)


def similarity(a: dict[str, Any], b: dict[str, Any]) -> tuple[float, dict[str, float]]:
    """Weighted similarity in [0, 1] plus the per-signal breakdown."""
    signals: dict[str, float] = {
        "mnemonics": _cosine(a.get("mnemonics", {}), b.get("mnemonics", {})),
        "size": _ratio(a.get("instructions", 0), b.get("instructions", 0)),
        "cfg": (_ratio(a.get("blocks", 0), b.get("blocks", 0)) + _ratio(a.get("edges", 0), b.get("edges", 0))) / 2,
    }
    weights = {"mnemonics": 0.45, "size": 0.2, "cfg": 0.2}
    callees = _jaccard(a.get("callees", []), b.get("callees", []))
    if callees is not None:
        signals["callees"] = callees
        weights["callees"] = 0.25
    strings = _jaccard(a.get("strings", []), b.get("strings", []))
    if strings is not None:
        signals["strings"] = strings
        weights["strings"] = 0.2
    total = sum(weights.values())
    score = sum(signals[k] * w for k, w in weights.items()) / total
    if a.get("normalized_hash") and a.get("normalized_hash") == b.get("normalized_hash"):
        score = max(score, 0.95)
    return round(score, 4), {k: round(v, 3) for k, v in signals.items()}


def _brief(f: dict[str, Any]) -> dict[str, Any]:
    return {"address": f["address"], "name": f["name"], "size": f["size"], "instructions": f["instructions"]}


def _status(a: dict[str, Any], b: dict[str, Any]) -> str:
    if a["exact_hash"] == b["exact_hash"]:
        return "identical"
    if a["normalized_hash"] == b["normalized_hash"]:
        return "same_structure"  # only addresses/immediates differ (e.g. relocation, rebuilt binary)
    return "modified"


def _unique_index(funcs: list[dict[str, Any]], key: str) -> dict[str, dict[str, Any]]:
    counts = Counter(f[key] for f in funcs)
    return {f[key]: f for f in funcs if counts[f[key]] == 1}


def compare(fa: list[dict[str, Any]], fb: list[dict[str, Any]], *, min_score: float = 0.75,
            max_candidates: int = 4000) -> dict[str, Any]:
    left = {f["address"]: f for f in fa}
    right = {f["address"]: f for f in fb}
    pairs: list[dict[str, Any]] = []

    def take(a: dict[str, Any], b: dict[str, Any], method: str, confidence: float,
             signals: dict[str, float] | None = None) -> None:
        left.pop(a["address"], None)
        right.pop(b["address"], None)
        p = {"a": _brief(a), "b": _brief(b), "method": method, "confidence": confidence, "status": _status(a, b),
             "size_delta": b["size"] - a["size"], "instruction_delta": b["instructions"] - a["instructions"]}
        if signals:
            p["signals"] = signals
        pairs.append(p)

    # 1. names (only real names; sub_XXXX differ across builds and mean nothing)
    by_name_b = {}
    name_counts_b = Counter(f["name"] for f in right.values() if f.get("named"))
    for f in right.values():
        if f.get("named") and name_counts_b[f["name"]] == 1:
            by_name_b[f["name"]] = f
    name_counts_a = Counter(f["name"] for f in left.values() if f.get("named"))
    for a in list(left.values()):
        if a.get("named") and name_counts_a[a["name"]] == 1 and a["name"] in by_name_b:
            take(a, by_name_b[a["name"]], "name", 1.0)

    # 2./3. unique hashes
    for key, method, conf in (("exact_hash", "exact_bytes", 0.99), ("normalized_hash", "normalized", 0.95)):
        ia = _unique_index(list(left.values()), key)
        ib = _unique_index(list(right.values()), key)
        for h, a in ia.items():
            if h in ib and a["address"] in left and ib[h]["address"] in right:
                take(a, ib[h], method, conf)

    # 4. similarity: greedy best-first over candidates of comparable size
    rest_a = sorted(left.values(), key=lambda f: f["instructions"])[:max_candidates]
    rest_b = sorted(right.values(), key=lambda f: f["instructions"])[:max_candidates]
    scored: list[tuple[float, str, str, dict[str, float]]] = []
    for a in rest_a:
        for b in rest_b:
            if _ratio(a["instructions"], b["instructions"]) < 0.5:
                continue
            s, sig = similarity(a, b)
            if s >= min_score:
                scored.append((s, a["address"], b["address"], sig))
    scored.sort(key=lambda t: -t[0])
    for s, aa, ba, sig in scored:
        if aa in left and ba in right:
            take(left[aa], right[ba], "similarity", s, sig)

    removed = [_brief(f) for f in left.values()]
    added = [_brief(f) for f in right.values()]
    return {"pairs": pairs, "removed": removed, "added": added}


def rank_similar(src: dict[str, Any], candidates: list[dict[str, Any]], top: int,
                 min_score: float) -> list[dict[str, Any]]:
    out = []
    for c in candidates:
        if c["address"] == src["address"] and c.get("_same_db"):
            continue
        s, sig = similarity(src, c)
        if s < min_score:
            continue
        r = {"function": _brief(c), "score": s, "signals": sig,
             "exact_match": c["exact_hash"] == src["exact_hash"],
             "same_structure": c["normalized_hash"] == src["normalized_hash"]}
        out.append(r)
    out.sort(key=lambda r: (-r["score"], r["function"]["address"]))
    return out[:top]
